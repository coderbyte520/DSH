/**
 * Debrand codemod: rewrites the DeepSeek identity (npm scope, product name,
 * repository URLs) across the workspace while PRESERVING the functional and
 * legally required identifiers.
 *
 * What changes:
 * - `@deepseek-ai/` npm scope → `NEW_SCOPE/` (package.json names, imports,
 *   peer deps, docs, cordis manifests — everywhere the token appears).
 * - `github.com/deepseek-ai/deepseek-harness` → the new repository URL.
 * - The product display name `DeepSeek Harness` → `NEW_PRODUCT`.
 * - The company display name `DeepSeek AI` → `NEW_ORG_DISPLAY`.
 *
 * What is deliberately NOT touched (functional or legal):
 * - `LICENSE` — MIT requires the original `Copyright (c) 2026 DeepSeek` notice
 *   to survive redistribution.
 * - Provider id `deepseek-official`, model ids `deepseek-v*`, package dir
 *   `packages/llm/llm-deepseek`, `DEEPSEEK_API_KEY` / `DEEPSEEK_BASE_URL` env
 *   names, `DSH_*` env prefix, `~/.dsh` home dir, the `dsh` bin name — all
 *   wired into fixtures, snapshots, and shipped configuration; renaming them
 *   breaks tests and user setups for zero brand value.
 * - `pnpm-lock.yaml` — regenerated by `pnpm install` after the rewrite.
 * - `node_modules`, `dist`, `lib`, `*.tsbuildinfo`, `.git`, `.dsh-build`,
 *   `.sessions`, `.env`.
 *
 * Brand artwork (`FishLogo.tsx`, `BrandWordmark.tsx`, `favicon.svg`) is also
 * left for a manual pass: the replacement logo is an asset swap in
 * `packages/client/ui-primitives/src/` and `apps/web/public/`, not a text
 * rewrite. The script prints those manual steps after applying.
 *
 * Usage: `tsx scripts/rebrand.ts [--apply]` — without `--apply` it only
 * reports per-rule hit counts. Re-running after `--apply` reports zero hits
 * (idempotent). Configuration lives in the CONFIG object below.
 */

import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = resolve(import.meta.dirname, '..')

/** Fill these in before running with --apply. */
const CONFIG = {
  /** New npm scope, e.g. '@your-org'. */
  NEW_SCOPE: '@your-org',
  /** New repository URL path, e.g. 'github.com/your-org/your-repo' (no protocol). */
  NEW_REPO_URL: 'github.com/your-org/your-repo',
  /** New product display name replacing "DeepSeek Harness". */
  NEW_PRODUCT: 'Your Harness',
  /** New org display name replacing "DeepSeek AI" (author/developer mentions). */
  NEW_ORG_DISPLAY: 'Your Org',
} as const

/** Ordered rewrite rules; each is a plain substring replacement. */
const RULES = [
  { id: 'repo-url', find: 'github.com/deepseek-ai/deepseek-harness', replace: CONFIG.NEW_REPO_URL },
  { id: 'product-name', find: 'DeepSeek Harness', replace: CONFIG.NEW_PRODUCT },
  { id: 'org-display', find: 'DeepSeek AI', replace: CONFIG.NEW_ORG_DISPLAY },
  { id: 'npm-scope', find: '@deepseek-ai/', replace: `${CONFIG.NEW_SCOPE}/` },
] as const

/** Text file extensions eligible for rewriting. */
const TEXT_EXTENSIONS = new Set([
  '.ts', '.tsx', '.js', '.mjs', '.cjs', '.tpl', '.json', '.yml', '.yaml',
  '.md', '.mdx', '.html', '.css', '.scss', '.svg', '.sh', '.py', '.toml',
  '.ini', '.txt', '.yaml.erb', '.gitignore', '', '.i18n.yaml',
])

/** Directory names skipped entirely (dependencies, build output, VCS, runtime). */
const SKIP_DIRS = new Set([
  'node_modules', '.git', 'dist', 'lib', '.dsh-build', '.sessions',
  '.turbo', 'coverage', '.vitest',
])

/** Individual files never rewritten: legal notice, lockfile, local secrets. */
const SKIP_FILES = new Set([
  'LICENSE', // MIT copyright preservation (do not debrand)
  'pnpm-lock.yaml', // regenerated by pnpm install
  '.env', // local credentials (gitignored anyway)
  'THIRD_PARTY_NOTICES.md', // factual dependency listing; regenerated by gen-third-party-notices
])

/** A file's per-rule hit counts from one pass. */
type HitMap = Map<string, number>

/** Walk the tree collecting text files eligible for rewriting. */
function collectFiles(dir: string, out: string[]): void {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name.startsWith('.git') && entry.isDirectory()) continue
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue
      collectFiles(join(dir, entry.name), out)
    } else {
      if (SKIP_FILES.has(entry.name)) continue
      const ext = entry.name.includes('.') ? entry.name.slice(entry.name.lastIndexOf('.')) : ''
      // Also accept compound suffixes like `README.i18n.yaml`.
      const compound = entry.name.endsWith('.i18n.yaml') ? '.i18n.yaml' : ext
      if (TEXT_EXTENSIONS.has(ext) || TEXT_EXTENSIONS.has(compound)) out.push(join(dir, entry.name))
    }
  }
}

/** Apply every rule to one buffer, recording hit counts. */
function rewrite(content: string, hits: HitMap): string {
  let out = content
  for (const rule of RULES) {
    if (!out.includes(rule.find)) continue
    const count = out.split(rule.find).length - 1
    hits.set(rule.id, (hits.get(rule.id) ?? 0) + count)
    out = out.replaceAll(rule.find, rule.replace)
  }
  return out
}

const apply = process.argv.includes('--apply')
const files: string[] = []
collectFiles(root, files)

const totalHits: HitMap = new Map()
let touched = 0

for (const file of files) {
  const content = readFileSync(file, 'utf8')
  const hits: HitMap = new Map()
  const next = rewrite(content, hits)
  if (hits.size === 0) continue
  touched++
  for (const [id, count] of hits) totalHits.set(id, (totalHits.get(id) ?? 0) + count)
  const rel = relative(root, file)
  if (apply) writeFileSync(file, next)
  console.log(`${apply ? 'rewrote' : 'would rewrite'} ${rel} (${[...hits].map(([id, n]) => `${id}:${n}`).join(', ')})`)
}

console.log('\n=== summary ===')
for (const rule of RULES) console.log(`${rule.id}: ${totalHits.get(rule.id) ?? 0} hits`)
console.log(`${touched} files ${apply ? 'rewritten' : 'would be rewritten'} (${files.length} scanned)`)
if (!apply) console.log('\nDry run only — pass --apply to write.')

if (apply) {
  console.log(`
=== manual steps after this codemod ===
1. pnpm install                      # regenerate pnpm-lock.yaml under the new scope
2. pnpm run build:lib:host           # rebuild contract layer under new import paths
3. Replace brand artwork (user-provided logo):
   - packages/client/ui-primitives/src/FishLogo.tsx
   - packages/client/ui-primitives/src/BrandWordmark.tsx
   - apps/web/public/favicon.svg
   - packages/client/ui-brand-official/  (official occupant package)
4. Review docs/ and website/ prose for "DeepSeek" mentions this codemod
   intentionally left (provider display names, model ids, legal notices).
5. Keep LICENSE's "Copyright (c) 2026 DeepSeek" — MIT obligation. Add a NOTICE
   line crediting the upstream project if you distribute this fork.
6. pnpm run rescope-vendor:check      # vendor rescope tooling still consistent`)
}
